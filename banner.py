def rgb(text, c):
    return f"\033[38;2;{c[0]};{c[1]};{c[2]}m{text}{RESET}"

def color_at(i, n):
    return RAINBOW[int(i * (len(RAINBOW)-1) / max(1, n-1))]

def make_rows(name):
    chars = [c if c in FONT else " " for c in name.upper()]
    rows = []
    for y in range(7):
        line = []
        for ch in chars:
            line.append(FONT[ch][y])
        rows.append("0".join(line))
    return rows

def render(name):
    cols = shutil.get_terminal_size((80, 24)).columns
    name = "".join(c if c.upper() in FONT else " " for c in name.upper()).strip() or "PHANTOM"
    # Each glyph is 5 columns plus one separator. Keep a little room for the frame.
    max_chars = max(1, min(18, (cols - 8) // 6))
    name = name[:max_chars]
    rows = make_rows(name)
    width = len(rows[0])
    inner = min(width + 4, cols - 4)
    print(CYAN + "╔" + "═" * inner + "╗" + RESET)
    # Colored block face with a darker offset outline to suggest the layered neon style.
    for y, row in enumerate(rows):
        output = []
        for x, bit in enumerate(row):
            if bit == "1":
                idx = min(len(name)-1, max(0, x // 6))
                face = color_at(idx, len(name))
                output.append(rgb("█", face))
            else:
                output.append(" ")
        line = "".join(output).rstrip()
        # Keep output within the terminal width.
        line = line[:max(1, cols - 8)]
        print(CYAN + "║ " + RESET + line + CYAN + " " * max(0, inner-len(line)) + " ║" + RESET)
    print(CYAN + "╚" + "═" * inner + "╝" + RESET)

